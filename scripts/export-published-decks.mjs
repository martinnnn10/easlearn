/**
 * Materialize decks published via the Authoring Studio into a static TS module.
 *
 * Reads deck_drafts WHERE status = 'published' (latest version per lesson key) and
 * writes shared/lessonDecks/_published.generated.ts, which lessonCardContent.ts
 * merges over the hand-authored bundle. Run after publishing, before a build:
 *
 *   pnpm db:export-decks
 *
 * This is the "make published drafts live on next build" path that fits the
 * current static-bundle architecture. (A future async DB-first resolver in
 * Lesson.tsx would make them live instantly without an export/redeploy.)
 */
import 'dotenv/config';
import mysql from 'mysql2/promise';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'shared', 'lessonDecks', '_published.generated.ts');

const DATABASE_URL = process.env.DATABASE_URL;
if (!DATABASE_URL) {
  console.error('DATABASE_URL not set');
  process.exit(1);
}

const connection = await mysql.createConnection(DATABASE_URL);

// Latest published version per (module_slug, lesson_slug).
const [rows] = await connection.execute(`
  SELECT d.module_slug, d.lesson_slug, d.deck
  FROM deck_drafts d
  JOIN (
    SELECT module_slug, lesson_slug, MAX(version) AS v
    FROM deck_drafts WHERE status = 'published'
    GROUP BY module_slug, lesson_slug
  ) latest
    ON d.module_slug = latest.module_slug
   AND d.lesson_slug = latest.lesson_slug
   AND d.version = latest.v
  WHERE d.status = 'published'
`);

const entries = {};
for (const r of rows) {
  const key = `${r.module_slug}/${r.lesson_slug}`;
  // deck column is JSON; mysql2 returns it already parsed.
  entries[key] = typeof r.deck === 'string' ? JSON.parse(r.deck) : r.deck;
}

const banner = `/**
 * AUTO-GENERATED — do not edit by hand.
 * Regenerated by scripts/export-published-decks.mjs (pnpm db:export-decks).
 * ${rows.length} published deck(s) at ${new Date().toISOString()}.
 */
import type { LessonCardDeck } from "../learningCardTypes";

export const PUBLISHED_DECKS: Record<string, LessonCardDeck> = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(OUT, banner, 'utf8');
console.log(`Wrote ${rows.length} published deck(s) → ${OUT}`);

await connection.end();
